async def run_test(page, output_dir, page_url):
    base=page.url.rstrip('/')
    try:
     result=await page.evaluate("""async () => (await fetch('/api/session',{method:'POST'})).json()""")
     print('FRESH_UI_TOKEN',result['token'])
     await page.evaluate('(token)=>localStorage.setItem("meantime-demo-token",token)',result['token'])
     await page.set_viewport_size({'width':360,'height':780})
     await page.goto(base+'/dashboard')
     await page.wait_for_selector('[data-testid="earnings-balance"]')
     await page.wait_for_timeout(1000)
     print('DEFAULT360 KPI CLIPPING',await page.locator('.kpi-value').evaluate_all("els=>els.map(e=>({text:e.textContent,width:e.clientWidth,scroll:e.scrollWidth,parent:e.parentElement.clientWidth}))"))
     await page.screenshot(path='/app/test_reports/browser_edge/automation_output/20261107_201923_1677ecec6360/default360.jpeg', type="jpeg", quality=40, full_page=False)
     await page.goto(base+'/insights')
     await page.get_by_test_id('insight-open-kv-cache').click()
     await page.wait_for_timeout(600)
     await page.get_by_test_id('reader-mark-read').click(force=True)
     await page.wait_for_timeout(400)
     assert await page.get_by_test_id('reader-mark-read').is_disabled()
     await page.get_by_test_id('sheet-close-button').click(force=True)
     await page.wait_for_timeout(400)
     print('PASS mobile insight drawer finish and close')
     await page.goto(base+'/rewards')
     await page.get_by_test_id('reward-node-stickers').click()
     await page.wait_for_timeout(600)
     await page.get_by_test_id('reward-claim-button').click(force=True)
     await page.wait_for_selector('[data-testid="reward-advance-button"]')
     await page.get_by_test_id('reward-advance-button').click(force=True)
     await page.wait_for_timeout(400)
     await page.get_by_test_id('reward-advance-button').click(force=True)
     await page.wait_for_selector('[data-testid="reward-delivered"]')
     print('PASS mobile reward drawer dispatch and delivery')
    except Exception as e: print('FAIL mobile edges',repr(e))
